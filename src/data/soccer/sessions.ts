export function getSessionById(id: string): PracticeSession | undefined {
	return sessions.find((s) => s.id === id);
}

export function getNextSession(fromDate = new Date()): PracticeSession {
	const iso = fromDate.toISOString().slice(0, 10);
	const upcoming = sessions.find((s) => s.date >= iso);
	return upcoming ?? sessions[sessions.length - 1]!;
}
